import Foundation

/// 设置窗口的摆位几何 —— **纯计算，不依赖 AppKit**。
///
/// ## 为什么放在 Core
///
/// 与 `PopoverLayout` / `StatusIconRenderer` 同理：把"布局规则"从 UI 框架里
/// 剥出来，才能在没有界面的环境下验证它。本机**无法**用脚本点开设置窗口
/// （菜单栏交互需要辅助功能权限），所以这条规则只能靠单测钉住。
///
/// ## 规则（用户三次实测反馈的产物）
///
/// | 版本 | 水平位置 | 结果 |
/// |------|---------|------|
/// | ① `window.center()` | 屏幕正中 | 与菜单栏图标完全脱钩 |
/// | ② 居中于**图标** | 跟随图标 | ✅ **用户确认：就是这个** |
/// | ③ 居中于屏幕 | 固定屏幕中 | ❌ 误解，已撤回（W2 单测挡住它复活） |
///
/// ⇒ 最终规则：**水平居中对齐图标**，垂直**顶边贴图标下沿**（保留 `gap`）。
///
/// ## ⚠️ 坐标系约定（踩过两次坑：搞反了窗口会跑到屏幕下方）
///
/// 与 `NSScreen.visibleFrame` / `NSWindow.frame` 同一套：**左下原点、y 向上增长**
/// ⇒ **屏幕顶部是大 y**。实测数据（诊断日志）：
///
/// ```
/// 菜单栏图标 frame = (1231, 1129, 25, 22)     ← 图标占 y 1129…1151
/// 屏幕可见区       = (55, 0, 1993, 1127)      ← 可见区底边 y=0、顶边 y=1127
/// ```
///
/// 由此读出两条容易搞错的事实：
/// * **菜单栏在可见区域之上 ⇒ 它的 y 更大**（图标 1129 > 可见区顶边 1127）；
/// * "顶边贴图标下沿"= `窗口顶边 = 图标.minY − gap`（图标下沿就是 `minY`），
///   而窗口的**底边**是 `origin.y`，顶边是 `origin.y + 高度`。
///
/// 所以正确的 `origin.y = 图标.minY − gap − 高度`。
/// 曾误按"y 向下增长"写成 `图标下沿 + gap`（= 1155），夹紧后变成 517 ——
/// 窗口被推到屏幕下方（用户实测："垂直错了，摆到屏幕下方了"）。
public enum SettingsWindowPlacement {

    /// 窗口顶边与图标下沿之间的间隙。
    ///
    /// 与 `NSPopover` 的观感对齐：贴太紧会像"粘"在菜单栏上。
    public static let gap: CGFloat = 4

    /// 算出设置窗口的原点。
    ///
    /// 坐标系：**左下原点、y 向上增长**。
    /// - Parameter windowSize: 窗口尺寸（含标题栏的 frame 尺寸）
    /// - Parameter screenVisibleFrame: 图标所在屏幕的**可见**区域
    ///   （用可见区域而非整屏：含菜单栏/Dock 的整屏会让夹紧失效）
    /// - Parameter iconFrame: 菜单栏图标按钮的 frame（同一坐标系）
    /// - Returns: 窗口原点（**底边**，与 `NSWindow.setFrameOrigin` 一致）。
    ///   水平**居中于图标**，垂直顶边贴图标下沿，并夹紧进可见区域。
    public static func origin(windowSize: CGSize,
                              screenVisibleFrame: CGRect,
                              iconFrame: CGRect) -> CGPoint {
        let visible = screenVisibleFrame

        // ① 水平：居中于**图标** —— 窗口跟着图标走（用户确认的行为）
        var x = iconFrame.midX - windowSize.width / 2
        // ② 夹紧到可见区域左右边界之内。
        //   状态栏图标会随其它菜单栏项目增减而左右移动，所以必须经得起两端极端位置：
        //   `x ∈ [可见区左边, 可见区右边 − 窗口宽]`，装得下时整窗可见。
        //
        //   两条约束的先后（窗口比可见区域还宽时二者不可同时满足）：
        //   先"右边界不越界"、再"左边界留在屏内" ⇒ 超宽窗口从可见区左边开始铺，
        //   宁可右边溢出也不整窗推到屏外（后者才是真正什么都看不到的情形）。
        //
        //   📌 实测记录：`max(min(x, maxX − w), minX)` 与直觉写法
        //   `min(max(x, minX), max(minX, maxX − w))` **在数学上完全等价**
        //   （`maxX − w < minX` 时两式都退化成 `minX`），所以这里不是"修 bug"，
        //   只是把优先级写得更显式。真正的保障来自 W11–W13 的穷举扫描测试。
        x = min(x, visible.maxX - windowSize.width)     // 先让右边不越界
        x = max(x, visible.minX)                        // 再保证左边留在屏内

        // ② 垂直：窗口顶边贴图标下沿，再让开 gap。
        //   y 向上增长 ⇒ 图标下沿是 `iconFrame.minY`，窗口由它**向下**铺开，
        //   故 origin.y（窗口底边）还要再减掉窗口高度。
        var y = iconFrame.minY - gap - windowSize.height

        // ★ 两条夹紧**必须都无条件施加**，顺序是"先保底边、后钉顶边"：
        //   ① `max(y, 可见区底边)`：窗口装得下时不许沉到可见区域下方（压住 Dock）；
        //   ② `min(y, 可见区顶边 − 高度)`：顶边绝不越出可见区域上方。
        //   ⚠️ 踩过的坑：曾把 ② 关在 `if 高度 <= 可见高度` 里面，于是超高窗口
        //      完全不被夹紧，顶边停在"图标下沿 − gap"（实测 1125）、
        //      一大半窗口跑到屏幕外。由 W6 单测抓出。
        //   为什么 ② 压在 ① 之后：窗口比可见区域还高时两条无法同时满足，
        //   必须让**顶部优先可见** —— 设置窗口的标签栏在最上面，
        //   那是用户最先要看的内容；底边溢出到 Dock 之下无所谓。
        y = max(y, visible.minY)
        y = min(y, visible.maxY - windowSize.height)

        return CGPoint(x: x, y: y)
    }
}
